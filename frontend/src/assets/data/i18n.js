const I18N = (() => {
  let currentLang = localStorage.getItem('km_lang') || 'en';
  if (!I18N_TRANSLATIONS[currentLang]) currentLang = 'en';

  function getLang() {
    return currentLang;
  }

  function setLang(langCode) {
    if (I18N_TRANSLATIONS[langCode]) {
      currentLang = langCode;
      localStorage.setItem('km_lang', langCode);
      return true;
    }
    return false;
  }

  function t(key) {
    const dict = I18N_TRANSLATIONS[currentLang] || I18N_TRANSLATIONS.en;
    if (dict[key] !== undefined) return dict[key];
    if (I18N_TRANSLATIONS.en[key] !== undefined) return I18N_TRANSLATIONS.en[key];
    return key;
  }

  function getAvailableLanguages() {
    return Object.keys(I18N_TRANSLATIONS).map(code => ({
      code,
      name: I18N_TRANSLATIONS[code].langName,
      nativeName: I18N_TRANSLATIONS[code].nativeName,
      flag: I18N_TRANSLATIONS[code].flag
    }));
  }

  return { getLang, setLang, t, getAvailableLanguages, translations: I18N_TRANSLATIONS };
})();

window.I18N = I18N;
